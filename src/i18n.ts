export const STRINGS: Record<Lang, Record<Key, string>> = { en: EN, de: DE }

let current: Lang = 'en'

export function setLang(lang: Lang): void {
  current = lang
}

export function getLang(): Lang {
  return current
}

/** The string for key in the current language, `{name}` placeholders filled from vars. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  return STRINGS[current][key].replace(/\{(\w+)\}/g, (m, name: string) => (name in vars ? String(vars[name]) : m))
}

/** The browser's language preference (navigator.languages): any `de*` entry → German, else English. */
export function browserLang(languages: readonly string[]): Lang {
  return languages.some((l) => l.toLowerCase().startsWith('de')) ? 'de' : 'en'
}

/** The language a press of the language button switches to. */
export function nextLang(lang: Lang): Lang {
  return LANGS[(LANGS.indexOf(lang) + 1) % LANGS.length]
}

export const levelLabel = (level: Level): string => t(`level_${level}`)
/** A technique's name in the current language (English names are lowercase); an unknown name passes through. */
export const techniqueName = (name: string): string => (`tech_${name}` in EN ? t(`tech_${name}` as Key) : name)
